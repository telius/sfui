-- ══════════════════════════════════════════════════════════════════════════════
--  Reverse Lookup & Query Helpers
-- ══════════════════════════════════════════════════════════════════════════════

local itemSourceCache   = nil
local dungeonNameCache  = nil
local questDungeonCache = nil

local function NormalizeName(str)
    if not str then return "" end
    return str:lower():gsub("[^%a%d]", "")
end

local function BuildCaches()
    if itemSourceCache then return end

    itemSourceCache   = {}
    dungeonNameCache  = {}
    questDungeonCache = {}

    local allSources = {
        sfui.dj_camelot.dungeons or {},
        sfui.dj_camelot.raids or {},
    }

    for _, list in ipairs(allSources) do
        for _, dungeon in ipairs(list) do
            -- Cache dungeon by ID and normalized name
            if dungeon.id then
                dungeonNameCache[dungeon.id:lower()] = dungeon
            end
            if dungeon.name then
                dungeonNameCache[NormalizeName(dungeon.name)] = dungeon
            end

            -- Cache item drops
            for _, boss in ipairs(dungeon.bosses or {}) do
                for _, itemID in ipairs(boss.items or {}) do
                    local rawID = type(itemID) == "table" and (itemID.id or itemID[1]) or itemID
                    local numID = tonumber(rawID)
                    if numID and not itemSourceCache[numID] then
                        itemSourceCache[numID] = {
                            dungeonID      = dungeon.id,
                            dungeonName    = dungeon.name,
                            bossName       = boss.name,
                            bossDisplayId  = boss.displayId,
                            dungeon        = dungeon,
                            boss           = boss,
                        }
                    end
                end
            end

            -- Cache quests (including chain steps)
            for _, quest in ipairs(dungeon.quests or {}) do
                local qID = tonumber(quest.id)
                if qID and not questDungeonCache[qID] then
                    questDungeonCache[qID] = {
                        dungeon = dungeon,
                        quest   = quest,
                    }
                end
                if quest.chain then
                    for _, step in ipairs(quest.chain) do
                        local sID = tonumber(step.id)
                        if sID and not questDungeonCache[sID] then
                            questDungeonCache[sID] = {
                                dungeon = dungeon,
                                quest   = quest,
                                step    = step,
                            }
                        end
                    end
                end
                if quest.chainStart and quest.chainStart.id then
                    local csID = tonumber(quest.chainStart.id)
                    if csID and not questDungeonCache[csID] then
                        questDungeonCache[csID] = {
                            dungeon = dungeon,
                            quest   = quest,
                            step    = quest.chainStart,
                        }
                    end
                end
            end
        end
    end
end

function sfui.dj_camelot.GetItemSource(itemID)
    if not itemID then return nil end
    local id = tonumber(itemID)
    if not id then return nil end
    BuildCaches()
    return itemSourceCache[id]
end

function sfui.dj_camelot.GetDungeonByName(name)
    if not name or name == "" then return nil end
    BuildCaches()
    local norm = NormalizeName(name)
    if dungeonNameCache[norm] then
        return dungeonNameCache[norm]
    end
    for key, d in pairs(dungeonNameCache) do
        if key:find(norm, 1, true) or norm:find(key, 1, true) then
            return d
        end
    end
    return nil
end

function sfui.dj_camelot.GetQuestDungeon(questID)
    if not questID then return nil end
    local id = tonumber(questID)
    if not id then return nil end
    BuildCaches()
    return questDungeonCache[id]
end

function sfui.dj_camelot.IsDungeonQuest(questID)
    return sfui.dj_camelot.GetQuestDungeon(questID) ~= nil
end

